#!/usr/bin/env python3
"""Genera source/cxx.c: imports libstdc++/libsupc++ del guest enlazados a la libstdc++ de VitaSDK.

iOS GCC 4.2 y VitaSDK comparten el ABI Itanium de 32 bits; solo cambia el mangling de size_t
(iOS: unsigned long 'm', Vita: unsigned int 'j'), así que se compara con j->m normalizado.

Uso: python3 -I tools/gen_cxx.py [Executable]   (por defecto game_app/BBD3; necesita nm de Xcode y VITASDK)
"""
import os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BIN = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'game_app', 'BBD3')
SDK = os.environ.get('VITASDK', os.path.expanduser('~/vitasdk'))
LIBS = [os.path.join(SDK, 'arm-vita-eabi', 'lib', l) for l in ('libstdc++.a', 'libsupc++.a')]
SKIP = re.compile(r'gxx_personality|_Unwind_')  # excepciones SjLj (iOS) != EHABI (Vita)

guest = subprocess.run(['nm', '-u', BIN], capture_output=True, text=True, check=True).stdout.split()

# Lo que ya implementan las otras tablas del loader tiene prioridad (imports_lookup va en orden).
src = ''.join(open(os.path.join(ROOT, 'source', f)).read()
              for f in os.listdir(os.path.join(ROOT, 'source')) if f.endswith('.c') and f != 'cxx.c' and not f.startswith('._'))
handled = set(re.findall(r'"(_[A-Za-z0-9_$]+)"', src)) | {'_' + n for n in re.findall(r'\b[FDV]\((\w+)', src)}

vita = {}  # nombre normalizado -> (nombre real, es_dato)
for lib in LIBS:
    out = subprocess.run([os.path.join(SDK, 'bin', 'arm-vita-eabi-nm'), '--defined-only', lib],
                         capture_output=True, text=True, check=True).stdout
    for line in out.splitlines():
        p = line.split()
        if len(p) == 3 and p[1] in 'TWDRBVu':
            vita.setdefault(p[2].replace('j', 'm'), (p[2], p[1] not in 'TW'))

funcs, data, missing = [], [], []
for g in sorted(set(guest)):
    if g in handled or SKIP.search(g) or not (g.startswith('__Z') or g.startswith('___cxa') or g == '___dynamic_cast'):
        continue
    hit = vita.get(g[1:].replace('j', 'm'))
    if not hit:
        missing.append(g)
    else:
        (data if hit[1] else funcs).append((g, hit[0]))

out = ['/**', ' * @file cxx.c',
       ' * @brief Guest libstdc++ / libsupc++ imports bound to the VitaSDK libstdc++ (old COW std::string ABI).',
       " * @details iOS GCC 4.2 and VitaSDK libstdc++ share the Itanium C++ ABI and 32-bit layouts; only the",
       " *          mangling of size_t differs (iOS: unsigned long 'm', Vita: unsigned int 'j').",
       ' *          Symbols are referenced through asm labels so the C compiler never needs their C++ types.',
       ' *          GENERATED by tools/gen_cxx.py from the guest import list and `nm libstdc++.a`: do not edit.',
       ' */', '#include "imports.h"', '']
out += [f'extern char cxx_f{i}[] __asm__("{v}");' for i, (_, v) in enumerate(funcs)]
out += [f'extern char cxx_d{i}[] __asm__("{v}");' for i, (_, v) in enumerate(data)]
out += ['', 'const import_entry cxx_imports[] = {']
out += [f'    F_RAW("{g}", cxx_f{i}),' for i, (g, _) in enumerate(funcs)]
out += [f'    {{"{g}", (uintptr_t)cxx_d{i}, 1}},' for i, (g, _) in enumerate(data)]
out += ['};', 'const int cxx_imports_count = sizeof(cxx_imports) / sizeof(cxx_imports[0]);', '']
open(os.path.join(ROOT, 'source', 'cxx.c'), 'w').write('\n'.join(out))
print(f'cxx.c: {len(funcs)} funciones, {len(data)} datos; sin equivalente en VitaSDK: {len(missing)}')
for m in missing:
    print('  ' + m)
